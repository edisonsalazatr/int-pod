# Applica i valori alternativi
updateSql = """MERGE INTO X3ETLCARATSAPS2 c USING (
	SELECT s.X3ETLCARATSAPS2ID,r.SAPTYPE,s2.CHAR_TYP,s2.DEC_TYP 
	FROM X3ETLCARATSAPS2 s
	JOIN X3ETLEQSAPS2 e ON e.EQUNR = s.OBJNR
	JOIN X3ETLSTZRULES r ON r.SAPCLASS = e.SAPCLASS AND r.RULE = 'AltValueEq' AND r.SAPNAME = s.NAME
	JOIN X3ETLCARATSAPS2 s2 ON s2.OBJNR = s.OBJNR AND s2.NAME = r.MAXNAME
	WHERE s.ROOTSTRNO IN (%s) AND s.CHAR_TYP IS NULL AND s.DEC_TYP IS NULL
) c2
ON (c2.X3ETLCARATSAPS2ID = c.X3ETLCARATSAPS2ID)
WHEN MATCHED THEN UPDATE
	SET c.CHAR_TYP = CASE
		 WHEN c2.SAPTYPE = 'ALNALN' THEN c2.CHAR_TYP
		 WHEN c2.SAPTYPE = 'ALNNUM' THEN REPLACE(RTRIM(TO_CHAR(c2.DEC_TYP , 'FM999999999999990.999999'), '.'),'.',',')
		 ELSE NULL
	END,
	c.DEC_TYP = CASE
		WHEN c2.SAPTYPE = 'NUMNUM' THEN c2.DEC_TYP
		ELSE NULL
	END"""%stazStrno
utils.executeQuery("UPDATE", "Applica i valori alternativi", updateSql)

