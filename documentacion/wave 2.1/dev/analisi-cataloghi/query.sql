select action, xcl.DESCRIPTION, versione, xcl.PRODVERSION, xcl.IDORIGINE, xcl.PLUSCREVNUM, xcl.IDDIFFORMITA, xcl.IDDIFFORMITA, gravita      from X3CATASSOCIAZIONE_LOGMERGE xcl 
where runid in (select max(runid) from X3CATASSOCIAZIONE_LOGMERGE)
order by "ACTION", xcl.IDORIGINE, PLUSCREVNUM, xcl.IDDIFFORMITA, xcl.IDINTERFERENZA    
; 

