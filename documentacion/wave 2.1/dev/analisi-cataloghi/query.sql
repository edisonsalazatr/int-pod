select xc.IDORIGINE, xc.PLUSCREVNUM, xc.IDDIFFORMITA, xc.IDINTERFERENZA, xc.GRAVITA      
from X3CATASSOCIAZIONE xc 
where xc.PLUSCREVNUM is not null and (xc.IDORIGINE, xc.PLUSCREVNUM) in (select b.idorigine, max(b.PLUSCREVNUM) from X3CATASSOCIAZIONE b where b.IDORIGINE = xc.IDORIGINE group by b.IDORIGINE)
order by xc.IDORIGINE, xc.PLUSCREVNUM, xc.IDDIFFORMITA, xc.IDINTERFERENZA, xc.GRAVITA;

